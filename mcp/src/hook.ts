// Claude Code hook entry point:  node hook.mjs session-start | post-edit   (hook input JSON on stdin)
// post-edit validates Defold files right after Claude writes them; session-start announces Defold projects.
import fs from 'node:fs';
import path from 'node:path';

const DEFOLD_FILE = /\.(script|gui_script|render_script|editor_script|lua|collection|go|gui|atlas|sprite|label|collisionobject|convexshape|factory|collectionfactory|collectionproxy|sound|camera|tilesource|tileset|tilemap|tilegrid|particlefx|font|material|compute|render|render_target|display_profiles|input_binding|gamepads|texture_profiles|model|mesh|animationset|cubemap)$|(^|[\\/])game\.project$/;
const MAX_REPORTED = 20;

interface HookInput {
  hook_event_name?: string;
  cwd?: string;
  tool_name?: string;
  tool_input?: { file_path?: string };
  source?: string;
}

async function readStdin(): Promise<HookInput> {
  const chunks: Buffer[] = [];
  for await (const c of process.stdin) chunks.push(c as Buffer);
  try {
    return JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}') as HookInput;
  } catch {
    return {};
  }
}

function findProjectRoot(start: string): string | undefined {
  let dir = start;
  for (let i = 0; i < 40; i++) {
    if (fs.existsSync(path.join(dir, 'game.project'))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) return undefined;
    dir = parent;
  }
  return undefined;
}

function hookMode(): 'strict' | 'warn' | 'off' {
  const v = (process.env.CLAUDE_PLUGIN_OPTION_HOOK_MODE ?? '').toLowerCase();
  return v === 'warn' || v === 'off' ? v : 'strict';
}

function emitContext(event: string, text: string): void {
  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: event, additionalContext: text } }));
}

async function postEdit(input: HookInput): Promise<number> {
  const file = input.tool_input?.file_path;
  if (!file || !DEFOLD_FILE.test(file)) return 0;
  const mode = hookMode();
  if (mode === 'off') return 0;
  const abs = path.resolve(input.cwd ?? process.cwd(), file);
  const root = findProjectRoot(path.dirname(abs));
  if (!root) return 0;
  const rel = path.relative(root, abs).split(path.sep);
  if (rel[0] === 'build' || rel[0] === '.internal') {
    emitContext('PostToolUse', `Note: ${path.relative(root, abs)} is generated by Defold (build output or cache) and will be overwritten. Edit the source resource instead.`);
    return 0;
  }
  let text: string;
  try {
    text = fs.readFileSync(abs, 'utf8');
  } catch {
    return 0;
  }
  // Heavy modules load only for Defold files.
  const [{ checkFile }, { loadProject }, { loadLibraries, makeResourceChecker }, { formatIssue }] = await Promise.all([
    import('./ddf/checkfile.js'),
    import('./env/project.js'),
    import('./env/projectfs.js'),
    import('./runtime/issues.js'),
  ]);
  const project = loadProject(root);
  const resource = '/' + rel.join('/');
  let exists: ((r: string) => boolean | undefined) | undefined;
  try {
    exists = makeResourceChecker(project, await loadLibraries(project));
  } catch {
    exists = undefined;
  }
  // References to files that do not exist yet are only warnings here: Claude often writes the referencing
  // file before the file it points to. The validate tool and builds report them as errors.
  const issues = checkFile(resource, text, { resourceExists: exists, missingRefSeverity: 'warning' });
  const errors = issues.filter((i) => i.severity === 'error');
  const warnings = issues.filter((i) => i.severity === 'warning');
  if (!errors.length && !warnings.length) return 0;

  const lines = [...errors, ...warnings].slice(0, MAX_REPORTED).map((i) => `- ${formatIssue(i)}`);
  const more = errors.length + warnings.length > MAX_REPORTED ? `\n… and ${errors.length + warnings.length - MAX_REPORTED} more (run the validate tool)` : '';
  if (errors.length && mode === 'strict') {
    process.stderr.write(`Defold check found ${errors.length} error(s) in ${resource} — fix before continuing:\n${lines.join('\n')}${more}\n`);
    return 2;
  }
  emitContext('PostToolUse', `Defold check for ${resource}:\n${lines.join('\n')}${more}`);
  return 0;
}

async function sessionStart(input: HookInput): Promise<number> {
  const cwd = input.cwd ?? process.cwd();
  let root = findProjectRoot(cwd);
  if (!root) {
    // A Defold project in a direct subfolder of the workspace.
    try {
      const sub = fs
        .readdirSync(cwd, { withFileTypes: true })
        .filter((e) => e.isDirectory() && !e.name.startsWith('.') && e.name !== 'node_modules')
        .map((e) => path.join(cwd, e.name))
        .filter((d) => fs.existsSync(path.join(d, 'game.project')));
      if (sub.length === 1) root = sub[0];
    } catch {
      // ignore
    }
  }
  if (!root) return 0;
  const { loadProject, editorPortFiles } = await import('./env/project.js');
  const { locateDefold } = await import('./env/locate.js');
  const project = loadProject(root);
  const install = locateDefold().install;
  const editorOpen = !!editorPortFiles(project).port;
  const parts = [
    `Defold project "${project.title}" at ${root}${install?.version ? ` (Defold ${install.version} installed)` : ' (Defold installation not found; run the status tool, which can also download bob.jar)'}.`,
    'Use the defold skill and the defold MCP tools: status, api (exact Lua signatures for this version), docs, read_resource/edit_resource (scene files), validate, build, run, logs, screenshot, inspect.',
    'Never edit build/ or .internal/. Defold files are checked automatically after each edit.',
  ];
  if (editorOpen) parts.push('The Defold editor has this project open: ask the user to save unsaved editor changes before editing files on disk.');
  emitContext('SessionStart', parts.join('\n'));
  return 0;
}

async function main(): Promise<void> {
  const event = process.argv[2] ?? '';
  const input = await readStdin();
  let code = 0;
  try {
    if (event === 'post-edit') code = await postEdit(input);
    else if (event === 'session-start') code = await sessionStart(input);
  } catch (err) {
    // Never block Claude because the checker itself failed.
    process.stderr.write(`defold hook error: ${(err as Error).message}\n`);
    code = 0;
  }
  process.exit(code);
}

void main();
